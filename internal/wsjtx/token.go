package wsjtx

import (
	"encoding/base64"
	"encoding/json"
	"errors"
	"strings"
)

// tokenPrefix marks a Noctalum v1 bridge token so the decoder can reject
// non-Noctalum pastes fast.  Bumping the digit is our escape hatch for
// breaking format changes; new optional fields alone don't need one.
const tokenPrefix = "noc1."

// BridgeToken is the decoded form of the "noc1.…" blob a Noctalum user
// copies out of the web UI.  It carries everything a bridge needs to
// authenticate and submit QSOs without any prior login: server URL,
// per-user helper token, target contest ID, and (optionally) the contest's
// expected station callsign for the client-side MyCall filter.
type BridgeToken struct {
	Server      string // "https://host[:port]" or bare "host:port"
	HelperToken string
	ContestID   int64
	StationCall string // may be empty for tokens minted before v0.76
}

// ErrInvalidToken is returned by DecodeBridgeToken when the input doesn't
// look like a Noctalum bridge token or the required fields are missing.
// The exact reason is exposed through error wrapping so a UI can render
// a specific hint.
var ErrInvalidToken = errors.New("invalid bridge token")

// EncodeBridgeToken produces the "noc1.…" string a user pastes into the
// bridge.  The Server + StationCall arguments are trimmed but not
// otherwise validated; the encoder is symmetric with the decoder.
func EncodeBridgeToken(tk BridgeToken) string {
	payload := struct {
		S  string `json:"s"`
		T  string `json:"t"`
		C  int64  `json:"c"`
		SC string `json:"sc,omitempty"`
	}{
		S:  strings.TrimSpace(tk.Server),
		T:  strings.TrimSpace(tk.HelperToken),
		C:  tk.ContestID,
		SC: strings.TrimSpace(tk.StationCall),
	}
	b, _ := json.Marshal(payload)
	return tokenPrefix + base64.RawURLEncoding.EncodeToString(b)
}

// DecodeBridgeToken parses the "noc1.…" blob generated by the web UI.
// Whitespace around the input is trimmed; the "https://" default is
// applied when the encoded server field carries only a bare host:port so
// pre-token config files that only carry a hostname keep working.
func DecodeBridgeToken(s string) (BridgeToken, error) {
	s = strings.TrimSpace(s)
	if !strings.HasPrefix(s, tokenPrefix) {
		return BridgeToken{}, ErrInvalidToken
	}
	raw, err := base64.RawURLEncoding.DecodeString(s[len(tokenPrefix):])
	if err != nil {
		return BridgeToken{}, ErrInvalidToken
	}
	var payload struct {
		S  string `json:"s"`
		T  string `json:"t"`
		C  int64  `json:"c"`
		SC string `json:"sc"`
	}
	if err := json.Unmarshal(raw, &payload); err != nil {
		return BridgeToken{}, ErrInvalidToken
	}
	tk := BridgeToken{
		Server:      strings.TrimSpace(payload.S),
		HelperToken: strings.TrimSpace(payload.T),
		ContestID:   payload.C,
		StationCall: strings.TrimSpace(payload.SC),
	}
	if tk.Server == "" || tk.HelperToken == "" || tk.ContestID <= 0 {
		return BridgeToken{}, ErrInvalidToken
	}
	if !strings.HasPrefix(tk.Server, "http://") && !strings.HasPrefix(tk.Server, "https://") {
		tk.Server = "https://" + tk.Server
	}
	return tk, nil
}

// BaseCallsign returns the "home" callsign component of cs by picking the
// longest slash-separated token that contains a digit and is at least 3
// characters long.  Mirrors internal/server/validate.go BaseCallsign so
// the client-side MyCall filter uses the same rule the server enforces on
// /api/wsjtx/qsos.  "DM2LAP/P" still matches "DM2LAP".
func BaseCallsign(cs string) string {
	cs = strings.ToUpper(strings.TrimSpace(cs))
	if cs == "" || !strings.Contains(cs, "/") {
		return cs
	}
	base := ""
	for _, p := range strings.Split(cs, "/") {
		if len(p) < 3 || !containsDigit(p) {
			continue
		}
		if len(p) > len(base) {
			base = p
		}
	}
	if base == "" {
		return cs
	}
	return base
}

func containsDigit(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] >= '0' && s[i] <= '9' {
			return true
		}
	}
	return false
}
